//! Narrow, byte-preserving normalization of the pinned Codex release lockfile.
//! Built directly with rustc; this helper has no registry or git dependencies.
use std::collections::BTreeSet;
use std::env;
use std::fs;
use std::path::Path;

type Result<T> = std::result::Result<T, String>;

struct Workspace {
    version: String,
    packages: BTreeSet<String>,
}

struct Normalized {
    lock: String,
    external: String,
    local_count: usize,
    external_count: usize,
}

fn field<'a>(text: &'a str, key: &str) -> Result<Option<&'a str>> {
    let values = text
        .lines()
        .filter_map(|line| line.split_once('='))
        .filter(|(name, _)| name.trim() == key)
        .map(|(_, value)| value.trim())
        .collect::<Vec<_>>();
    match values.as_slice() {
        [] => Ok(None),
        [value] => Ok(Some(*value)),
        _ => Err(format!("duplicate field {key}")),
    }
}

fn quoted(text: &str) -> Result<&str> {
    let value = text
        .strip_prefix('"')
        .and_then(|s| s.strip_suffix('"'))
        .ok_or_else(|| "expected a simple quoted value".to_string())?;
    if value.is_empty()
        || !value
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || b"-_.+".contains(&c))
    {
        return Err("unsupported quoted value".into());
    }
    Ok(value)
}

fn section<'a>(text: &'a str, name: &str) -> Result<Option<&'a str>> {
    let marker = format!("[{name}]");
    let mut starts = text.match_indices(&marker);
    let Some((start, _)) = starts.next() else {
        return Ok(None);
    };
    if starts.next().is_some() {
        return Err(format!("duplicate section {name}"));
    }
    let rest = text[start + marker.len()..].trim_start_matches('\n');
    let end = rest.find("\n[").unwrap_or(rest.len());
    Ok(Some(&rest[..end]))
}

fn collect_packages(path: &Path, names: &mut BTreeSet<String>) -> Result<()> {
    let manifest = path.join("Cargo.toml");
    if manifest.is_file() {
        let text = fs::read_to_string(&manifest).map_err(|e| e.to_string())?;
        if let Some(package) = section(&text, "package")? {
            if field(package, "version.workspace")? == Some("true") {
                let name = quoted(field(package, "name")?.ok_or("missing package name")?)?;
                if !names.insert(name.to_string()) {
                    return Err(format!("duplicate workspace package {name}"));
                }
            }
        }
    }
    for entry in fs::read_dir(path).map_err(|e| e.to_string())? {
        let entry = entry.map_err(|e| e.to_string())?;
        if entry.file_type().map_err(|e| e.to_string())?.is_dir()
            && !matches!(entry.file_name().to_str(), Some("target" | ".git"))
        {
            collect_packages(&entry.path(), names)?;
        }
    }
    Ok(())
}

fn workspace(path: &Path) -> Result<Workspace> {
    let manifest = fs::read_to_string(path.join("Cargo.toml")).map_err(|e| e.to_string())?;
    let package = section(&manifest, "workspace.package")?.ok_or("missing workspace.package")?;
    let version =
        quoted(field(package, "version")?.ok_or("missing workspace version")?)?.to_string();
    if version == "0.0.0" {
        return Err("workspace release version must differ from 0.0.0".into());
    }
    let mut packages = BTreeSet::new();
    collect_packages(path, &mut packages)?;
    if packages.is_empty() {
        return Err("no version.workspace packages found".into());
    }
    Ok(Workspace { version, packages })
}

fn normalize(workspace: &Workspace, original: &str) -> Result<Normalized> {
    if original.contains('\r') || !original.ends_with('\n') {
        return Err("expected canonical LF-terminated Cargo.lock".into());
    }
    let mut blocks = original.split("[[package]]\n");
    let header = blocks.next().ok_or("missing lock header")?;
    if header != "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n" {
        return Err("unexpected pinned lockfile header".into());
    }
    let mut lock = header.to_string();
    let mut external = String::new();
    let mut local_names = BTreeSet::new();
    let mut external_count = 0;
    for block in blocks {
        let name = quoted(field(block, "name")?.ok_or("missing lock package name")?)?;
        let version = quoted(field(block, "version")?.ok_or("missing lock package version")?)?;
        lock.push_str("[[package]]\n");
        if field(block, "source")?.is_some() {
            // The complete external record is copied byte for byte, including
            // version, registry/git revision, checksum and dependency edges.
            external_count += 1;
            external.push_str("[[package]]\n");
            external.push_str(block);
            lock.push_str(block);
        } else {
            if !workspace.packages.contains(name)
                || !local_names.insert(name.to_string())
                || version != "0.0.0"
                || field(block, "checksum")?.is_some()
            {
                return Err(format!("unexpected local package record {name}"));
            }
            let old = "version = \"0.0.0\"\n";
            if block.matches(old).count() != 1 {
                return Err(format!("noncanonical version line for {name}"));
            }
            let new = format!("version = \"{}\"\n", workspace.version);
            let updated = block.replacen(old, &new, 1);
            if updated.replacen(&new, old, 1) != block {
                return Err(format!("non-version change in {name}"));
            }
            lock.push_str(&updated);
        }
    }
    if local_names != workspace.packages {
        return Err(
            "lock local package names do not exactly match version.workspace manifests".into(),
        );
    }
    for line in original.lines().map(str::trim) {
        if let Some(reference) = line.strip_prefix('"') {
            let mut fields = reference.split_whitespace();
            if fields.next().is_some_and(|name| local_names.contains(name))
                && fields
                    .next()
                    .is_some_and(|version| version.trim_end_matches([',', '"']) == "0.0.0")
            {
                return Err("version-qualified local dependency reference requires review".into());
            }
        }
    }
    // Independently rebuild the external block stream from the derived lock.
    let unchanged = lock
        .split("[[package]]\n")
        .skip(1)
        .filter(|block| field(block, "source").is_ok_and(|s| s.is_some()))
        .map(|block| format!("[[package]]\n{block}"))
        .collect::<String>();
    if unchanged != external {
        return Err("external package records changed".into());
    }
    Ok(Normalized {
        lock,
        external,
        local_count: local_names.len(),
        external_count,
    })
}

fn run() -> Result<()> {
    let args = env::args_os().skip(1).collect::<Vec<_>>();
    if args.len() != 4 {
        return Err(
            "usage: normalize-lock WORKSPACE ORIGINAL_LOCK DERIVED_LOCK EXTERNAL_RECORDS".into(),
        );
    }
    let workspace = workspace(Path::new(&args[0]))?;
    let original = fs::read_to_string(&args[1]).map_err(|e| e.to_string())?;
    let normalized = normalize(&workspace, &original)?;
    for (path, contents) in [
        (&args[2], &normalized.lock),
        (&args[3], &normalized.external),
    ] {
        if Path::new(path).exists() {
            return Err("normalization outputs must not already exist".into());
        }
        fs::write(path, contents).map_err(|e| e.to_string())?;
    }
    println!(
        "{{\"local_packages\":{},\"external_packages\":{},\"external_records_unchanged\":true}}",
        normalized.local_count, normalized.external_count
    );
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("normalize-lock: {error}");
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const HEADER: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n";
    const LOCAL: &str = "[[package]]\nname = \"codex-core\"\nversion = \"0.0.0\"\ndependencies = [\n \"external\",\n]\n\n";
    const EXTERNAL: &str = "[[package]]\nname = \"external\"\nversion = \"0.0.0\"\nsource = \"git+https://example.invalid/upstream?rev=abc#abc\"\nchecksum = \"unchanged\"\ndependencies = [\n \"other 1.2.3\",\n]\n";

    fn workspace_fixture() -> Workspace {
        Workspace {
            version: "0.172.0".into(),
            packages: BTreeSet::from(["codex-core".into()]),
        }
    }

    #[test]
    fn changes_only_local_versions_and_preserves_complete_external_record() {
        let original = format!("{HEADER}{LOCAL}{EXTERNAL}");
        let result = normalize(&workspace_fixture(), &original).unwrap();
        assert_eq!(result.local_count, 1);
        assert_eq!(result.external_count, 1);
        assert_eq!(result.external, EXTERNAL);
        assert_eq!(
            result.lock,
            format!(
                "{HEADER}{}{EXTERNAL}",
                LOCAL.replace("\"0.0.0\"", "\"0.172.0\"")
            )
        );
    }

    #[test]
    fn refuses_unknown_local_package_or_manifest_missing_from_lock() {
        let original = format!("{HEADER}{LOCAL}{EXTERNAL}");
        let mut workspace = workspace_fixture();
        workspace.packages.clear();
        assert!(normalize(&workspace, &original).is_err());
        workspace.packages.insert("codex-core".into());
        workspace.packages.insert("missing".into());
        assert!(normalize(&workspace, &original).is_err());
    }

    #[test]
    fn refuses_repeated_or_previously_modified_local_versions() {
        assert!(normalize(&workspace_fixture(), &format!("{HEADER}{LOCAL}{LOCAL}")).is_err());
        let modified = LOCAL.replace("\"0.0.0\"", "\"0.172.0\"");
        assert!(normalize(&workspace_fixture(), &format!("{HEADER}{modified}")).is_err());
    }

    #[test]
    fn refuses_a_checksum_on_a_local_record_and_duplicate_fields() {
        let checksummed = LOCAL.replace("dependencies", "checksum = \"unexpected\"\ndependencies");
        assert!(normalize(&workspace_fixture(), &format!("{HEADER}{checksummed}")).is_err());
        let duplicate = LOCAL.replace("dependencies", "version = \"0.0.0\"\ndependencies");
        assert!(normalize(&workspace_fixture(), &format!("{HEADER}{duplicate}")).is_err());
    }

    #[test]
    fn refuses_version_qualified_local_dependency_references() {
        let local = LOCAL.replace(" \"external\",", " \"codex-core 0.0.0\",");
        assert!(normalize(&workspace_fixture(), &format!("{HEADER}{local}")).is_err());
    }

    #[test]
    fn reads_only_the_declared_manifest_section() {
        let manifest = "[package]\nname = \"local\"\nversion.workspace = true\n\n[dependencies]\nname = \"unrelated\"\n";
        let package = section(manifest, "package").unwrap().unwrap();
        assert_eq!(field(package, "name").unwrap(), Some("\"local\""));
        assert!(section(manifest, "workspace.package").unwrap().is_none());
    }
}
